from __future__ import annotations

import locale
import os

LANGS = {"en": "English", "pt": "Português (BR)", "es": "Español"}
AUTO_LANG = "auto"
_lang = "en"


def detect() -> str:
    """Seleciona o idioma padrão de acordo com a localidade do sistema."""
    try:
        import ctypes
        ui_language = ctypes.windll.kernel32.GetUserDefaultUILanguage()
        names = [locale.windows_locale.get(ui_language, "")]
    except (AttributeError, OSError):
        system_locale = ""
        for variable in ("LC_ALL", "LC_MESSAGES", "LANG"):
            value = os.environ.get(variable, "")
            # C and POSIX select locale-neutral formatting, with no UI language.
            if value and value.split(".", 1)[0].upper() not in ("C", "POSIX"):
                system_locale = value
                break
        names = [*os.environ.get("LANGUAGE", "").split(":"), system_locale]
    for name in names:
        code = name.replace("-", "_").split("_", 1)[0].split(".", 1)[0].lower()
        if code in LANGS:
            return code
    return "en"


def set_lang(code: str):
    global _lang
    if code in LANGS:
        _lang = code


def get_lang() -> str:
    return _lang


def has(key: str) -> bool:
    return key in STRINGS


def tr(key: str, **kw) -> str:
    entry = STRINGS.get(key)
    if entry is None:
        return key
    en, pt = entry
    text = SPANISH.get(key, en) if _lang == "es" else (pt or en) if _lang == "pt" else en
    return text.format(**kw) if kw else text


